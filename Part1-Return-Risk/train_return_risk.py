# 12. TASK 8 - SUBGROUP ANALYSIS
# ============================================================

def subgroup_analysis(
    rf_model,
    X_test,
    y_test,
    t_rf
):

    """
    Task 8:

    Calculate recall and precision separately for:

        1. product_category
        2. payment_method

    We use t*_rf, the F1-maximising Random Forest threshold.
    """

    print("\n")
    print("=" * 60)
    print("TASK 8 - SUBGROUP / ROOT-CAUSE ANALYSIS")
    print("=" * 60)

    # Get probabilities
    probabilities = rf_model.predict_proba(X_test)[:, 1]

    # Apply Random Forest threshold
    predictions = (probabilities >= t_rf).astype(int)

    # Make a copy of test data
    subgroup_data = X_test.copy()

    subgroup_data["actual"] = (y_test.values)

    subgroup_data["prediction"] = predictions

    # Product category
    # --------------------------------------------------------

    category_results = []

    for category in sorted(subgroup_data["product_category"].unique()):
        subset = subgroup_data[
            subgroup_data["product_category"]
            == category
        ]

        category_recall = recall_score(
            subset["actual"],
            subset["prediction"],
            pos_label=1,
            zero_division=0
        )

        category_precision = precision_score(
            subset["actual"],
            subset["prediction"],
            pos_label=1,
            zero_division=0
        )

        category_results.append({
            "product_category": category,
            "orders": len(subset),
            "recall": category_recall,
            "precision": category_precision
        })

    category_df = pd.DataFrame(category_results)


    print("\nPerformance by product category:")
    print(category_df.to_string(index=False))

    # Payment method
    # --------------------------------------------------------

    payment_results = []

    for payment in sorted(
        subgroup_data["payment_method"].unique()
    ):

        subset = subgroup_data[
            subgroup_data["payment_method"]
            == payment
        ]

        payment_recall = recall_score(
            subset["actual"],
            subset["prediction"],
            pos_label=1,
            zero_division=0
        )

        payment_precision = precision_score(
            subset["actual"],
            subset["prediction"],
            pos_label=1,
            zero_division=0
        )

        payment_results.append({
            "payment_method": payment,
            "orders": len(subset),
            "recall": payment_recall,
            "precision": payment_precision
        })

    payment_df = pd.DataFrame(payment_results)

    print("\nPerformance by payment method:")
    print(payment_df.to_string(index=False))


    # Overall performance at t*_rf
    # --------------------------------------------------------

    overall_recall = recall_score(
        y_test,
        predictions,
        pos_label=1,
        zero_division=0
    )

    overall_precision = precision_score(
        y_test,
        predictions,
        pos_label=1,
        zero_division=0
    )

    print("\nOverall Random Forest performance at t*_rf:")
    print("Recall:",f"{overall_recall:.4f}")

    print("Precision:", f"{overall_precision:.4f}")



    # Save subgroup results
    Path('../results').mkdir(parents=True, exist_ok=True) # Ensure results directory exists
    category_df.to_csv(
        "../results/subgroup_product_category.csv",
        index=False
    )

    payment_df.to_csv(
        "../results/subgroup_payment_method.csv",
        index=False
    )

    return category_df, payment_df


