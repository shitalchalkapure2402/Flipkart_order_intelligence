def analyze_feature_importance(
    rf_model,
    X_test,
    y_test
):

    """
    Task 7:

    Extract Random Forest impurity-based feature importance.

    Then calculate permutation importance on the held-out
    test set.

     """

    print("\n")
    print("=" * 60)
    print("TASK 7 - FEATURE IMPORTANCE")
    print("=" * 60)

    # Get the preprocessing step
    fitted_preprocessor = rf_model.named_steps["preprocessor"]

    # Get the Random Forest
    fitted_rf = rf_model.named_steps["classifier"]

    # Get feature names after preprocessing
    feature_names = fitted_preprocessor.get_feature_names_out()

    # Get impurity-based feature importance
    impurity_importance = fitted_rf.feature_importances_

    # Create a DataFrame
    importance_df = pd.DataFrame({
        "feature": feature_names,
        "importance": impurity_importance
    })

    # Sort from highest to lowest
    importance_df = importance_df.sort_values(
        "importance",
        ascending=False
    )

    # Top 5 transformed features
    top_5 = importance_df.head(5).copy()

    print("\nTop 5 impurity-based features:")
    print(top_5.to_string(index=False))

    # --------------------------------------------------------
    # Map transformed features back to original features
    # --------------------------------------------------------

    def get_original_feature(feature_name):

        if feature_name.startswith("numeric__"):
            return feature_name.replace(
                "numeric__",
                ""
            )

        if feature_name.startswith("categorical__"):
            categorical_name = feature_name.replace(
                "categorical__","")

            if categorical_name.startswith("product_category_"):
                     return "product_category"

            if categorical_name.startswith("payment_method_"):
                     return "payment_method"

        return feature_name

    top_5["original_feature"] = (
        top_5["feature"]
        .apply(get_original_feature)
    )

    print("\nTop 5 with original feature names:")
    print(top_5.to_string(index=False))


    # --------------------------------------------------------
    # Permutation importance
    # --------------------------------------------------------
    #
    # Important:
    # We pass the ORIGINAL X_test to the complete pipeline.
    # The pipeline handles preprocessing internally.
    #
    # Therefore permutation importance measures the effect
    # of shuffling an original input feature.
    # --------------------------------------------------------

    permutation_result = permutation_importance(
        rf_model,
        X_test,
        y_test,
        scoring="roc_auc",
        n_repeats=10,
        random_state=42,
        n_jobs=-1
    )

    permutation_df = pd.DataFrame({
        "feature": X_test.columns,
        "permutation_importance": (
            permutation_result.importances_mean
        )
    })

    permutation_df = permutation_df.sort_values(
        "permutation_importance",
        ascending=False
    )

    print("\nPermutation importance:")
    print(permutation_df.to_string(index=False))

    # --------------------------------------------------------
    # Compare original top-5 features
    # --------------------------------------------------------

    original_top_features = (
        top_5["original_feature"]
        .drop_duplicates()
        .tolist()
    )

    comparison_rows = []

    for feature in original_top_features:

        # Total impurity importance belonging to
        # this original feature
        impurity_value = (
            importance_df[
                importance_df["feature"].apply(
                    get_original_feature
                ) == feature
            ]["importance"]
            .sum()
        )

        # Permutation importance for the original feature
        permutation_matches = permutation_df[
            permutation_df["feature"] == feature
        ]

        if len(permutation_matches) > 0:
            permutation_value = (
                permutation_matches[
                    "permutation_importance"
                ].iloc[0]
            )
        else:
            permutation_value = np.nan

        comparison_rows.append({
            "feature": feature,
            "impurity_importance": impurity_value,
            "permutation_importance": permutation_value
        })

    comparison_df = pd.DataFrame(
        comparison_rows
    )

    comparison_df = comparison_df.sort_values(
        "impurity_importance",
        ascending=False
    )

    print("\nImpurity vs permutation comparison:")
    print(comparison_df.to_string(index=False))

    # Save results
    Path('../results').mkdir(parents=True, exist_ok=True) # Ensure results directory exists
    importance_df.to_csv(
        "../results/random_forest_feature_importance.csv",
        index=False
    )

    permutation_df.to_csv(
        "../results/random_forest_permutation_importance.csv",
        index=False
    )

    comparison_df.to_csv(
        "../results/importance_comparison.csv",
        index=False
    )

    return (
        importance_df,
        permutation_df,
        comparison_df
    )


