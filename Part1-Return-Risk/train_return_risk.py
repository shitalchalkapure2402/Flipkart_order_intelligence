def run_logistic_regression(X_train,X_test,
                            y_train,y_test,
                            preprocessor
                            ):

    """

    Train Logistic Regression using class_weight='balanced'.
    Because returned orders
    are less common than non-returned orders.

    At the default threshold of 0.5 we calculate:
        Accuracy
        F1
        Recall
        Precision
        ROC-AUC

    Then we sweep thresholds from 0.10 to 0.90
    using a maximum step size of 0.02.
    """

    print("\n")
    print("=" * 60)
    print("TASK 5 - LOGISTIC REGRESSION")
    print("=" * 60)

    logistic_model = Pipeline(
        steps=[
            (
                "preprocessor",
                preprocessor
            ),
            (
                "classifier",
                LogisticRegression(
                    class_weight="balanced",
                    max_iter=1000,
                    random_state=42
                )
            )
        ]
    )

    logistic_model.fit(X_train, y_train)
    y_pred = logistic_model.predict(X_test)
    y_probability = logistic_model.predict_proba(X_test)[:, 1]

    # Calculate default metrics
    accuracy = accuracy_score(y_test, y_pred)

    f1 = f1_score(y_test, y_pred, pos_label=1, zero_division=0)

    recall = recall_score(y_test, y_pred, pos_label=1, zero_division=0)

    precision = precision_score(y_test, y_pred, pos_label=1, zero_division=0)

    roc_auc = roc_auc_score(y_test, y_probability)

    print("\nDefault threshold = 0.50")

    print("Accuracy:", f"{accuracy:.4f}")
    print("F1:", f"{f1:.4f}")
    print("Recall:", f"{recall:.4f}")
    print("Precision:", f"{precision:.4f}")
    print("ROC-AUC:", f"{roc_auc:.4f}")

    # --------------------------------------------------------
    # Threshold sweep
    # --------------------------------------------------------

    threshold_results = []

    # 0.10 to 0.90 with step 0.01
    # This satisfies the requirement of at most 0.02.
    thresholds = np.arange(
        0.10,
        0.901,
        0.01
    )

    for threshold in thresholds:

        # Convert probabilities into predictions
        threshold_predictions = (
            y_probability >= threshold
        ).astype(int)

        threshold_f1 = f1_score(
            y_test,
            threshold_predictions,
            pos_label=1,
            zero_division=0
        )

        threshold_recall = recall_score(
            y_test,
            threshold_predictions,
            pos_label=1,
            zero_division=0
        )

        threshold_precision = precision_score(
            y_test,
            threshold_predictions,
            pos_label=1,
            zero_division=0
        )

        threshold_results.append({
            "threshold": threshold,
            "f1": threshold_f1,
            "recall": threshold_recall,
            "precision": threshold_precision
        })

    threshold_df = pd.DataFrame(
        threshold_results
    )

    # Find threshold with maximum F1
    best_row = threshold_df.loc[
        threshold_df["f1"].idxmax()
    ]

    best_threshold = best_row["threshold"]
    best_f1 = best_row["f1"]
    best_recall = best_row["recall"]
    best_precision = best_row["precision"]

    print("\nBest Logistic Regression threshold")
    print("----------------------------------")

    print("Threshold:", f"{best_threshold:.2f}")

    print("F1:", f"{best_f1:.4f}")

    print("Recall:", f"{best_recall:.4f}")

    print("Precision:", f"{best_precision:.4f}")

    # Recall improvement compared with default threshold
    recall_difference = (
        best_recall - recall
    )

    precision_difference = (
        best_precision - precision
    )

    print(
        "\nRecall improvement:",
        f"{recall_difference * 100:.2f}",
        "percentage points"
    )

    print(
        "Precision change:",
        f"{precision_difference * 100:.2f}",
        "percentage points"
    )

    # Save threshold results
    Path('../results').mkdir(parents=True, exist_ok=True) # Ensure results directory exists
    threshold_df.to_csv(
        "../results/logistic_threshold_results.csv",
        index=False
    )

    return logistic_model, threshold_df


