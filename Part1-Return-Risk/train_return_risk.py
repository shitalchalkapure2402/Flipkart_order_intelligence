def run_random_forest(
    X_train,
    X_test,
    y_train,
    y_test,
    preprocessor
):

    """
    Task 6:
    Train and tune a Random Forest.

    Required:
        class_weight='balanced'
        random_state=42

    Grid Search:
        n_estimators = [100, 200]
        max_depth = [6, 10, None]

    Evaluation:
        ROC-AUC

    Cross-validation:
        5-fold StratifiedKFold
    """

    print("\n")
    print("=" * 60)
    print("TASK 6 - RANDOM FOREST + GRID SEARCH")
    print("=" * 60)

    # Create Random Forest
    random_forest = RandomForestClassifier(
        class_weight="balanced",
        random_state=42
    )

    # Put preprocessing and Random Forest together
    rf_pipeline = Pipeline(
        steps=[("preprocessor", preprocessor),
               ("classifier", random_forest)
              ])

    # Required parameter grid
    parameter_grid = {
        "classifier__n_estimators": [100, 200],
        "classifier__max_depth": [6, 10, None]
        }

    # Five-fold stratified cross-validation
    cross_validation = StratifiedKFold(n_splits=5, shuffle=True,random_state=42)

    # GridSearchCV
    grid_search = GridSearchCV(
        estimator= rf_pipeline,
        param_grid= parameter_grid,
        scoring= "roc_auc",
        cv= cross_validation,
        n_jobs= -1,
        return_train_score= False
    )

    print("\nRunning GridSearchCV...")
    print("------------------------")

    # Train all combinations
    grid_search.fit( X_train, y_train)

    # Best model
    best_rf_model = grid_search.best_estimator_

    # Best parameters
    best_parameters = grid_search.best_params_

    # Best cross-validation score
    best_cv_roc_auc = grid_search.best_score_

    # Test probabilities
    test_probability = best_rf_model.predict_proba(X_test)[:, 1]

    # Test ROC-AUC
    test_roc_auc = roc_auc_score(y_test, test_probability)

    print("\nBest Random Forest Parameters")
    print("-----------------------------")

    print(best_parameters)

    print("\nBest cross-validated ROC-AUC:", f"{best_cv_roc_auc:.4f}")

    print("Held-out test ROC-AUC:", f"{test_roc_auc:.4f}")

    print(
        "Difference between CV and test ROC-AUC:",
        f"{abs(best_cv_roc_auc - test_roc_auc):.4f}"
    )

    # Save GridSearch results
    Path('../results').mkdir(parents=True, exist_ok=True) # Ensure results directory exists
    grid_results = pd.DataFrame(grid_search.cv_results_)

    grid_results.to_csv(
        "../results/random_forest_grid_search.csv",
        index=False)

    return best_rf_model, grid_search


