def find_rf_threshold(rf_model, X_test, y_test):

    """
    Task 7 / Task 9 requirement:

    Run the threshold sweep AGAIN using the Random Forest's
    own predict_proba output.

    We must NOT reuse the Logistic Regression threshold.

    The resulting threshold is t*_rf.
    """

    print("\n")
    print("=" * 60)
    print("RANDOM FOREST THRESHOLD SWEEP")
    print("=" * 60)

    # Get Random Forest probabilities
    rf_probability = rf_model.predict_proba(
        X_test
    )[:, 1]

    threshold_results = []

    # 0.10 to 0.90 with 0.01 steps
    thresholds = np.arange(
        0.10,
        0.901,
        0.01
    )

    for threshold in thresholds:

        predictions = (
            rf_probability >= threshold
        ).astype(int)

        f1 = f1_score(
            y_test,
            predictions,
            pos_label=1,
            zero_division=0
        )

        recall = recall_score(
            y_test,
            predictions,
            pos_label=1,
            zero_division=0
        )

        precision = precision_score(
            y_test,
            predictions,
            pos_label=1,
            zero_division=0
        )

        threshold_results.append({
            "threshold": threshold,
            "f1": f1,
            "recall": recall,
            "precision": precision
        })

    threshold_df = pd.DataFrame(
        threshold_results
    )

    # Find maximum F1
    best_row = threshold_df.loc[
        threshold_df["f1"].idxmax()
    ]

    t_rf = float(
        best_row["threshold"]
    )

    print("\nF1-maximising Random Forest threshold")
    print("-------------------------------------")

    print(
        "t*_rf:",
        f"{t_rf:.2f}"
    )

    print(
        "F1:",
        f"{best_row['f1']:.4f}"
    )

    print(
        "Recall:",
        f"{best_row['recall']:.4f}"
    )

    print(
        "Precision:",
        f"{best_row['precision']:.4f}"
    )

    # Save results
    Path('../results').mkdir(parents=True, exist_ok=True) # Ensure results directory exists
    threshold_df.to_csv(
        "../results/random_forest_threshold_results.csv",
        index=False
    )

    return t_rf, threshold_df


